package data

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.lang.reflect.Proxy

/**
 * Room の Migration の検証。
 * MigrationTestHelper は端末(Instrumentation)が要るので JVM の単体テストでは使えない。
 * 代わりに、Migration.migrate が流す SQL を記録して確かめ、エンティティの定義と食い違わないことも見る。
 * SQLite 上での実行は、エミュレータで version 1 の DB から更新して確かめる。
 */
class AppMigrationsTest {

    private fun recordedSql(migration: androidx.room.migration.Migration): List<String> {
        val executed = mutableListOf<String>()
        val db = Proxy.newProxyInstance(
            javaClass.classLoader,
            arrayOf(androidx.sqlite.db.SupportSQLiteDatabase::class.java)
        ) { _, method, args ->
            if (method.name == "execSQL") executed += args[0] as String
            null
        } as androidx.sqlite.db.SupportSQLiteDatabase
        migration.migrate(db)
        return executed
    }

    @Test
    fun `migration 1 to 2 only adds the stoppedByUser column with default 0`() {
        val migration = AppMigrations.MIGRATION_1_2
        assertEquals(1, migration.startVersion)
        assertEquals(2, migration.endVersion)

        val sql = recordedSql(migration)
        assertEquals(1, sql.size)
        assertEquals(
            "ALTER TABLE `products` ADD COLUMN `stoppedByUser` INTEGER NOT NULL DEFAULT 0",
            sql.single()
        )
        // 既存データを消す文は含まない
        assertTrue(sql.none { it.contains("DROP", ignoreCase = true) || it.contains("DELETE", ignoreCase = true) })
    }


    private fun sourceText(name: String): String =
        listOf("data/$name", "../data/$name").map { java.io.File(it) }.first { it.exists() }.readText(Charsets.UTF_8)

    @Test
    fun `migration list has no gap and ends at the database version declared in AppDatabase`() {
        val all = AppMigrations.ALL.sortedBy { it.startVersion }
        assertEquals(1, all.first().startVersion)
        all.zipWithNext().forEach { (a, b) -> assertEquals(a.endVersion, b.startVersion) }
        // Room の注釈は実行時に読めないので、ソースの宣言と比べる
        val declared = Regex("""version\s*=\s*(\d+)""").find(sourceText("AppDatabase.kt"))!!.groupValues[1].toInt()
        assertEquals(declared, all.last().endVersion)
        assertEquals(2, declared)
    }

    @Test
    fun `entity column definition matches the migration (default 0, not null)`() {
        val entity = sourceText("entity/ProductEntity.kt")
        assertTrue(entity.contains("@ColumnInfo(defaultValue = \"0\")"))
        assertTrue(entity.contains("val stoppedByUser: Boolean = false"))
        // 既存の行は印なしになる
        assertTrue(AppMigrations.ADD_STOPPED_BY_USER.endsWith("INTEGER NOT NULL DEFAULT 0"))
    }

    @Test
    fun `exported schema version 2 has the same column definition as the migration when present`() {
        val schema = listOf("schemas/data.AppDatabase/2.json", "app/schemas/data.AppDatabase/2.json")
            .map { java.io.File(it) }.firstOrNull { it.exists() }
        org.junit.Assume.assumeTrue("schema JSON is generated by the build (exportSchema)", schema != null)
        val text = schema!!.readText(Charsets.UTF_8)
        // Room が期待する products の列定義。ALTER の列定義と同じ文字列で終わる
        val columnDefinition = AppMigrations.ADD_STOPPED_BY_USER.substringAfter("ADD COLUMN ")
        assertTrue(text.contains(columnDefinition))
    }
}
